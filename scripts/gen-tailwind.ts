#!/usr/bin/env bun
/**
 * LIMINAL — the Tailwind bridge.
 *
 * Tailwind v4 reads its theme from CSS, not from a JavaScript preset. So the
 * bridge is a `@theme` block, and every value in it comes from the engine —
 * the same source `index.css` and the DTCG file read.
 *
 * The point is not to give Tailwind its own copy of the tokens. It is to let a
 * consumer write `bg-liminal-s3` and get the same surface the engine resolves,
 * from the same number.
 *
 * Run: bun scripts/gen-tailwind.ts
 */
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LiminalLayoutEngine as L } from '../src/engine/liminal-layout-engine';
import { LiminalMotionEngine as M } from '../src/engine/liminal-motion-engine';
import { LiminalColorEngine as C } from '../src/engine/liminal-color-engine';
import { LADDER, getTextStyle } from '../src/engine/spec-engine';
import { PERSIAN_FONT_STACK } from '../src/engine/liminal-persian';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, '../src/engine/liminal-tailwind.css');

const lines: string[] = [];
const push = (s: string) => lines.push(s);

push('/**');
push(' * LIMINAL · TAILWIND BRIDGE');
push(' *');
push(' * GENERATED by scripts/gen-tailwind.ts. Do not edit; re-run the script.');
push(' *');
push(' * Tailwind v4 reads its theme from CSS. This maps the engine\'s tokens to');
push(' * Tailwind\'s utility names, so `bg-liminal-s3` and `resolveSurface({ role:');
push(' * \'panel\' })` are the same colour from the same number.');
push(' *');
push(' * NOT a second copy of the tokens. Every value below is read from the engine,');
push(' * and `tailwind.test.ts` asserts it stays that way.');
push(' *');
push(' * ONE THING TO KNOW: Tailwind only generates a utility for a class it finds');
push(' * in a scanned source file. `bg-liminal-s3` in a string that Tailwind never');
push(' * sees produces nothing — not a broken colour, no rule at all. That is');
push(' * Tailwind\'s JIT and not this bridge, but it is the first thing that looks');
push(' * like a bug when a dynamic class name does not work.');
push(' */');
push('');
push('@theme {');

// ── colours ────────────────────────────────────────────────────────────────
push('  /* the ladder, by step and by role */');
LADDER.forEach((hex, i) => push(`  --color-liminal-s${i}: ${hex};`));
const ROLES = ['canvas', 'chrome', 'work', 'panel', 'control', 'floating', 'popover', 'modal', 'ceiling'];
ROLES.forEach((role, i) => push(`  --color-liminal-${role}: ${LADDER[i]};`));

push('');
push('  /* text roles — the alpha is derived from a contrast floor, not picked */');
(['primary', 'secondary', 'tertiary', 'quaternary'] as const).forEach((role) =>
  push(`  --color-liminal-text-${role}: ${getTextStyle(role, 2).color};`),
);

push('');
push('  /* semantic roles — the hue is a convention, the rest is derived */');
(['SUCCESS', 'WARNING', 'DANGER', 'INFO'] as const).forEach((k) => {
  const s = (C.SEMANTICS as any)[k];
  push(`  --color-liminal-${k.toLowerCase()}: ${s.solid};`);
  push(`  --color-liminal-${k.toLowerCase()}-text: ${s.text};`);
});

push('');
push('  /* the extended spectrum */');
(C.EXTENDED_SPECTRUM as any[]).forEach((h) => push(`  --color-liminal-hue-${h.hue}: ${h.hex};`));

// ── spacing, radius, sizes ─────────────────────────────────────────────────
push('');
push('  /* spacing — the atom is 4px; below it, elements read as touching */');
Object.entries(L.SPACING).forEach(([k, v]) => push(`  --spacing-liminal-${k}: ${v}px;`));

push('');
push('  /* radius — the concentric law: an inner radius is the outer minus the padding */');
Object.entries(L.RADIUS).forEach(([k, v]) => push(`  --radius-liminal-${k}: ${v}px;`));

push('');
push('  /* control heights — md IS the accessible minimum */');
Object.entries(L.CONTROL).forEach(([k, v]) => push(`  --spacing-liminal-control-${k}: ${v}px;`));
push(`  --spacing-liminal-target: ${L.TARGET.min}px;`);
push(`  --spacing-liminal-hairline: ${L.BORDER.hairline}px;`);

// ── type ───────────────────────────────────────────────────────────────────
push('');
push('  /* type — the size is fluid, so the utility is a var() and not a px */');
Object.entries(L.TYPOGRAPHY).forEach(([lvl, t]) => {
  push(`  --text-liminal-${lvl}: ${L.getTypeSizeCss(Number(lvl))};`);
  push(`  --text-liminal-${lvl}--line-height: ${t.lh};`);
  push(`  --text-liminal-${lvl}--letter-spacing: ${t.ls};`);
  push(`  --text-liminal-${lvl}--font-weight: ${t.weight};`);
});

push('');
push('  /* fonts */');
push('  --font-liminal: ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif;');
push(`  --font-liminal-fa: ${PERSIAN_FONT_STACK};`);

// ── motion ─────────────────────────────────────────────────────────────────
push('');
push('  /* motion */');
Object.entries(M.DURATION).forEach(([k, v]) => push(`  --duration-liminal-${k}: ${v}ms;`));

push('}');
push('');

const css = lines.join('\n');
writeFileSync(OUT, css);

const count = (css.match(/^\s+--/gm) ?? []).length;
console.log(`wrote ${OUT}`);
console.log(`  ${count} Tailwind theme variables`);
