#!/usr/bin/env node
/**
 * LIMINAL — self-host the Latin face.
 *
 * `--liminal-font-en` shipped as a system stack and the body asked for `Inter`,
 * which was never loaded: every page fell back to whatever the machine had, so
 * the type scale was measured against a face nobody chose. Inter is the
 * reference Latin face here for the same reason Vazirmatn is the Persian one —
 * it is designed for screens, its metrics are stable, and it is open.
 *
 * Downloads the variable Latin subset into `public/fonts/` and writes a
 * stylesheet that points at the local file. Swapping the import is the change.
 *
 *   node scripts/fetch-latin-font.mjs
 *
 * Then, in src/index.css, import `./engine/liminal-fonts-latin.css`.
 */
import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const OUT_DIR = resolve(ROOT, 'public/fonts');
const OUT_CSS = resolve(ROOT, 'src/engine/liminal-fonts-latin.css');

const VERSION = '5.2.5';
const FILE = 'inter-latin-wght-normal.woff2';
const URL = `https://cdn.jsdelivr.net/npm/@fontsource-variable/inter@${VERSION}/files/${FILE}`;

mkdirSync(OUT_DIR, { recursive: true });
const dest = resolve(OUT_DIR, FILE);

if (!existsSync(dest)) {
  const res = await fetch(URL);
  if (!res.ok) {
    console.error(`fetch failed: ${res.status} ${res.statusText} — ${URL}`);
    process.exit(1);
  }
  const buf = Buffer.from(await res.arrayBuffer());
  // A woff2 file starts with the signature 'wOF2'. Checking it is the
  // difference between shipping a font and shipping an error page.
  if (buf.subarray(0, 4).toString('latin1') !== 'wOF2') {
    console.error('downloaded file is not a woff2');
    process.exit(1);
  }
  writeFileSync(dest, buf);
  console.log(`wrote ${dest} (${(buf.length / 1024).toFixed(1)} KB)`);
} else {
  console.log(`already present: ${dest}`);
}

writeFileSync(
  OUT_CSS,
  `/**
 * LIMINAL · LATIN FONT — self-hosted
 *
 * GENERATED by scripts/fetch-latin-font.mjs. Do not edit; re-run the script.
 *
 * Inter, variable weight, Latin subset. The subset is why this is small: a page
 * that renders no Latin downloads nothing, and the Persian face is a separate
 * file with its own unicode-range.
 *
 * The engine's type scale is measured in \`lh\` and \`rem\`, so it is face-agnostic
 * by construction — but a face still has to be LOADED for the measurement to
 * mean anything.
 */

@font-face {
  font-family: 'Inter';
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  src: url('/fonts/${FILE}') format('woff2-variations');
  unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA,
    U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193,
    U+2212, U+2215, U+FEFF, U+FFFD;
}
`,
  'utf8',
);
console.log(`wrote ${OUT_CSS}`);
