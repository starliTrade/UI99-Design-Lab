#!/usr/bin/env node
/**
 * LIMINAL — self-host the Persian face.
 *
 * The shipped `liminal-fonts.css` points at a CDN so the system works out of
 * the box. A production consumer should not depend on someone else's server for
 * a font on the critical path, and a consumer in a network that cannot reach
 * that CDN should not depend on it at all.
 *
 * This downloads the face into `public/fonts/`, verifies its metrics against
 * the contract the line-height floor was derived from, and writes a stylesheet
 * that points at the local files. Swapping the import is the whole change.
 *
 *   node scripts/fetch-font.mjs
 *
 * Then, in src/index.css, replace:
 *   @import "./engine/liminal-fonts.css";
 * with:
 *   @import "./engine/liminal-fonts-selfhosted.css";
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const VERSION = '33.0.3';
const BASE = `https://cdn.jsdelivr.net/npm/vazirmatn@${VERSION}/fonts/webfonts`;

/**
 * The metrics the line-height floor rests on. If the face changes, these change
 * and `PERSIAN_LINE_HEIGHT_FLOOR` must be re-derived — so they are checked
 * rather than assumed.
 */
const EXPECTED = { unitsPerEm: 2048, ascender: 2100, descender: -1100, lineGap: 0 };

/** Read `head`, `hhea` and `OS/2` out of a TTF. */
function readMetrics(buf) {
  if (buf.readUInt32BE(0) !== 0x00010000) throw new Error('not a TrueType file');
  const numTables = buf.readUInt16BE(4);
  const tables = {};
  for (let i = 0; i < numTables; i++) {
    const off = 12 + i * 16;
    tables[buf.toString('latin1', off, off + 4)] = buf.readUInt32BE(off + 8);
  }
  const unitsPerEm = buf.readUInt16BE(tables.head + 18);
  const ascender = buf.readInt16BE(tables.hhea + 4);
  const descender = buf.readInt16BE(tables.hhea + 6);
  const lineGap = buf.readInt16BE(tables.hhea + 8);
  return { unitsPerEm, ascender, descender, lineGap };
}

const files = [
  { name: 'Vazirmatn[wght].woff2', url: `${BASE}/Vazirmatn%5Bwght%5D.woff2` },
];

mkdirSync(resolve(ROOT, 'public/fonts'), { recursive: true });

for (const f of files) {
  const res = await fetch(f.url);
  if (!res.ok) throw new Error(`${f.url} -> ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  writeFileSync(resolve(ROOT, 'public/fonts', f.name), buf);
  console.log(`  wrote public/fonts/${f.name}  (${(buf.length / 1024).toFixed(1)} KB)`);
}

// Verify the metrics against the contract, from the TTF rather than the woff2
// (woff2 is compressed; the TTF carries the same tables uncompressed).
const ttf = await fetch(`https://cdn.jsdelivr.net/npm/vazirmatn@${VERSION}/fonts/ttf/Vazirmatn-Regular.ttf`);
const metrics = readMetrics(Buffer.from(await ttf.arrayBuffer()));
const ok = Object.entries(EXPECTED).every(([k, v]) => metrics[k] === v);
const floor = (metrics.ascender - metrics.descender + metrics.lineGap) / metrics.unitsPerEm;
console.log(`\n  metrics: ${JSON.stringify(metrics)}`);
console.log(`  natural line-height: ${floor}`);
console.log(`  ${ok ? 'MATCHES' : 'DOES NOT MATCH'} the contract in liminal-persian.ts`);
if (!ok) {
  console.error('\n  The face changed. Re-derive PERSIAN_LINE_HEIGHT_FLOOR before shipping it.');
  process.exit(1);
}

const css = `/**
 * LIMINAL · PERSIAN FONT — self-hosted
 *
 * GENERATED by scripts/fetch-font.mjs. Do not edit; re-run the script.
 *
 * Same face, same metrics, served from this origin:
 *   unitsPerEm ${metrics.unitsPerEm} · ascender ${metrics.ascender} · descender ${metrics.descender} · lineGap ${metrics.lineGap}
 *   natural line-height = ${floor}
 *
 * That number is the line-height floor in liminal-persian.ts. A different face
 * has different metrics and the floor must be re-derived from them.
 */

@font-face {
  font-family: 'Vazirmatn';
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  src: url('/fonts/Vazirmatn%5Bwght%5D.woff2') format('woff2-variations');
  unicode-range: U+0600-06FF, U+0750-077F, U+0870-088E, U+0890-0891, U+0898-08E1,
    U+08E3-08FF, U+200C-200E, U+2010-2011, U+204F, U+2E41, U+FB50-FDFF, U+FE70-FEFF;
}

@font-face {
  font-family: 'Vazirmatn';
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  src: url('/fonts/Vazirmatn%5Bwght%5D.woff2') format('woff2-variations');
  unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA,
    U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+2074, U+20AC, U+2122, U+2191,
    U+2193, U+2212, U+2215, U+FEFF, U+FFFD;
}

:lang(fa) {
  font-family: var(--liminal-font-fa);
  line-height: var(--liminal-line-height-fa-floor, ${floor});
  letter-spacing: 0;
}
`;
writeFileSync(resolve(ROOT, 'src/engine/liminal-fonts-selfhosted.css'), css);
console.log('\n  wrote src/engine/liminal-fonts-selfhosted.css');
console.log('  swap the import in src/index.css to use it.');
