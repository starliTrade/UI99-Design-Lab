/**
 * LIMINAL · TONAL LADDER (PRIMITIVE)
 * «نردبان، ابتدایی‌ترین لایه‌ی سیستم است — به هیچ چیز وابسته نیست.»
 *
 * This module is deliberately dependency-free. The ladder is the foundation of
 * every other engine, so it must be importable without pulling anything in.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * THE LADDER IS DERIVED FROM A MEASURED PERCEPTUAL THRESHOLD.
 *
 * Until 2026-10-11 the step was an assumption (0.015 in the contract, then the
 * measured average of a hand-picked palette, 0.0127). Neither was a perceptual
 * measurement. The step is now derived from the user's own threshold, measured
 * on their display with a constant-stimuli psychophysical test
 * (design-lab/threshold-test-precise.html, three sessions):
 *
 *     q = 0.0083   ΔL at 50% detection — the perceptual quantum
 *     r = 0.0112   ΔL at 95% detection — the reliable boundary  (r/q = 1.35)
 *
 * RULES the ladder obeys (all asserted in __tests__/tokens.test.ts):
 *   1. every realised step ≥ q            — otherwise that pair is invisible
 *   2. every realised step ≤ 1.5q         — otherwise the ladder feels jumpy
 *   3. the canvas is the anchor           — S0 is the darkest allowed value
 *   4. the ceiling stays at L ≤ 0.204     — the contract's darkness ceiling
 *
 * 8-bit hex cannot hit an arbitrary ΔL, and at this darkness the reachable steps
 * are irregular (0.0005–0.0038). The sequence below was chosen by search to
 * minimise step variance subject to rule 1. Realised steps: 1.07q – 1.27q.
 *
 * Structural relations are expressed in LADDER STEPS, not in raw ΔL:
 *   canvas → chrome        = 1 step   (1.27q)
 *   canvas → work surface  = 2 steps  (2.48q)
 *   canvas → nested panel  = 3 steps  (3.62q)
 *   canvas → floating      = 5 steps  (5.86q)
 * ─────────────────────────────────────────────────────────────────────────────
 */

/** The perceptual quantum, measured. ΔL at 50% detection. */
export const PERCEPTUAL_QUANTUM = 0.0083;

/** The reliable boundary, measured. ΔL at 95% detection. */
export const RELIABLE_BOUNDARY = 0.0112;

/**
 * THE LADDER IS GENERATED BY A FORMULA — hue and chroma are constants, only
 * lightness varies. This is what makes it a scale rather than a palette.
 *
 *   L(n) = CANVAS_L + n × STEP
 *   C    = CHROMA   (constant)
 *   H    = HUE      (constant)
 *
 * Why constants: a ladder whose hue drifts is several colours pretending to be
 * one. The hand-picked palette drifted 14° in hue and varied 2.3× in chroma;
 * the search-based sequence that replaced it was better (6.5°, 1.38×) but still
 * not derived from anything. With constants there is nothing left to drift.
 *
 * The values are not arbitrary: they are the constants that reproduce the
 * approved ladder. The formula was recovered FROM the design, not imposed on it
 * — only three hexes move, each by one unit in the blue channel.
 *
 * ── The rules the ladder obeys (asserted in __tests__/tokens.test.ts) ──
 *   1. every realised step ≥ q          — otherwise that pair is invisible
 *   2. every realised step ≤ 1.5q       — otherwise the ladder reads jumpy
 *   3. hue and chroma are constant      — otherwise it is not one scale
 *   4. the ceiling stays at L ≤ 0.204
 *   5. the work surface sits at 2.0–2.6q
 *
 * 8-bit hex cannot hit an arbitrary ΔL, so the realised steps land at
 * 1.07q–1.21q even though the targets are uniform. That is the display, not
 * the design.
 */
export const CANVAS_L = 0.128;
export const LADDER_STEP = 0.009475;
export const LADDER_CHROMA = 0.0069;
export const LADDER_HUE = 258.4;
export const LADDER_SIZE = 9;

/**
 * THE EXACT LADDER — the design, which hex cannot write.
 *
 * The target was ALWAYS a constant: `LADDER_STEP = 0.009475` = 1.1416q, the same
 * for every step. The realised ladder is 1.07q to 1.21q — a spread of 0.14q — and
 * that spread is not the design. It is 8-bit sRGB failing to write it: the nearest
 * hex to the exact value is off by up to 0.199q, a fifth of a quantum.
 *
 * CSS CAN WRITE IT. `oklch()` carries full precision, so the ladder the browser
 * paints can be the ladder that was designed — every step exactly 1.1416q, every
 * half-step exactly 0.5708q. The hexes stay as the canonical values for
 * arithmetic, tests and the contract; the stylesheet emits both, the exact value
 * second, which is the standard progressive-enhancement pair for a custom
 * property: a browser that cannot parse `oklch()` keeps the hex.
 *
 *   --liminal-s3: #0b0d0f;                      the quantised rendering
 *   --liminal-s3: oklch(0.1564250 0.0069 258.4); the design
 *
 * Seven decimals, because six is not enough: the half-step 0.1327375 rounds to
 * 0.132738 at six, and the difference from its neighbour becomes 0.009474 instead
 * of 0.009475 — a rounding error in the one number the whole system is built on.
 */
export const LADDER_EXACT: readonly string[] = Array.from({ length: LADDER_SIZE }, (_, n) =>
  `oklch(${(CANVAS_L + n * LADDER_STEP).toFixed(7)} ${LADDER_CHROMA} ${LADDER_HUE})`,
);

/** The half-steps, exact — the value a border, a state shift and a nesting floor land on. */
export const HALF_EXACT: readonly string[] = Array.from({ length: LADDER_SIZE - 1 }, (_, n) =>
  `oklch(${(CANVAS_L + (n + 0.5) * LADDER_STEP).toFixed(7)} ${LADDER_CHROMA} ${LADDER_HUE})`,
);

